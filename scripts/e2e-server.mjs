const workerEnv = { ...process.env, WRANGLER_LOG_PATH: '.wrangler/logs' };
if (process.env.E2E_REAL_SUPABASE === '1') {
  delete workerEnv.E2E_TEST;
}
if (
  process.env.TEST_SANITY_READ === '1' ||
  process.env.EDITORIAL_LOCAL === '0'
) {
  delete workerEnv.EDITORIAL_LOCAL;
}
if (typeof sanityReadToken !== 'undefined' && sanityReadToken) {
  workerEnv.SANITY_API_READ_TOKEN = sanityReadToken;
}
workerEnv.OFFERS_INGEST_SECRET =
  process.env.OFFERS_INGEST_SECRET || 'test-collector-secret-32-chars-long';

const hasTls =
  process.env.E2E_TLS_KEY &&
  process.env.E2E_TLS_CERT &&
  existsSync(process.env.E2E_TLS_KEY) &&
  existsSync(process.env.E2E_TLS_CERT);

const upstreamProcess = useWorker
  ? spawn(
      'npx',
      ['wrangler', 'dev', '--port', '3101', '--ip', '127.0.0.1', '--local'],
      {
        stdio: 'inherit',
        env: workerEnv,
      },
    )
  : spawn(
      process.execPath,
      ['node_modules/next/dist/bin/next', 'start', '--port', '3101'],
      {
        stdio: 'inherit',
        env: {
          ...process.env,
          NEXT_PUBLIC_SITE_URL:
            process.env.NEXT_PUBLIC_SITE_URL ||
            (hasTls ? 'https://localhost:3100' : 'http://localhost:3100'),
          ADMIN_USER_ID:
            process.env.ADMIN_USER_ID || '11111111-1111-1111-1111-111111111111',
          ADMIN_EMAIL: process.env.ADMIN_EMAIL || 'ana@exemplo.dev',
          OFFERS_INGEST_SECRET:
            process.env.OFFERS_INGEST_SECRET ||
            'test-collector-secret-32-chars-long',
        },
      },
    );

const handleRequest = (incoming, outgoing) => {
  const headers = { ...incoming.headers };
  if (hasTls && !headers['x-forwarded-proto']) {
    headers['x-forwarded-proto'] = 'https';
  }
  const upstream = request(
    {
      hostname: '127.0.0.1',
      port: 3101,
      path: incoming.url,
      method: incoming.method,
      headers,
    },
    (response) => {
      outgoing.writeHead(response.statusCode || 502, response.headers);
      response.pipe(outgoing);
    },
  );
  // Sem resposta do upstream no arranque, 502 em vez de conexão abandonada: o primeiro
  // pedido do Playwright não falha por tempo de boot do Next.
  upstream.on('error', () => {
    outgoing.writeHead(502);
    outgoing.end('Servidor inicializando.');
  });
  incoming.pipe(upstream);
};

const server = hasTls
  ? createHttpsServer(
      {
        key: readFileSync(process.env.E2E_TLS_KEY),
        cert: readFileSync(process.env.E2E_TLS_CERT),
      },
      handleRequest,
    )
  : createHttpServer(handleRequest);
server.listen(3100, '0.0.0.0');
// Ordem do teardown importa: fecha o proxy e o TLS antes de matar o processo upstream, para que nenhuma
// requisição em voo encontre um upstream derrubado antes do emissor.
const stop = () => {
  server.close();
  closeFaultProxy();
  upstreamProcess.kill('SIGTERM');
};
process.on('SIGTERM', stop);
process.on('SIGINT', stop);
upstreamProcess.on('exit', (code) => {
  server.close();
  closeFaultProxy();
  process.exitCode = code || 0;
});
